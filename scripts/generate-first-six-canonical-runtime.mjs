import assert from "node:assert/strict";
import { readFileSync, writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";

const sourceUrl = new URL("../docs/content/FIRST_SIX_CANONICAL_READING_MANUSCRIPT_2026-08-21.md", import.meta.url);
const outputUrl = new URL("../content/first-six-canonical-reading-manuscript.js", import.meta.url);
const manuscript = readFileSync(fileURLToPath(sourceUrl), "utf8");
const expectedCounts = Object.freeze({ wikiwhy: 10, threadit: 9, faceplace: 8, mycorner: 9, yahuh: 9, viewtube: 8 });
const decks = {};

function field(record, label) {
  return record.match(new RegExp(`\\*\\*${label}:\\*\\* (.+?)(?: {2})?$`, "mu"))?.[1]?.trim() ?? "";
}

function plainMarkdownLink(value) {
  const match = value.match(/^\[([^\]]+)\]\((.+)\)$/u);
  return match ? Object.freeze({ label: match[1], url: match[2] }) : Object.freeze({ label: value, url: null });
}

for (const section of manuscript.split(/^## /mu).slice(1)) {
  const [site] = section.split("\n", 1);
  if (!(site in expectedCounts)) continue;
  const records = section.split(/^### \d+\. /mu).slice(1).map((record) => {
    const title = record.split("\n", 1)[0].trim();
    const id = field(record, "Canonical ID").replaceAll("`", "");
    const form = field(record, "Form");
    const spokenWordCount = Number(field(record, "Spoken word count"));
    const spoken = record.split("**Spoken passage**", 2)[1]?.split("**Comprehension check**", 1)[0]?.trim() ?? "";
    const comprehension = record.split("**Comprehension check**", 2)[1]?.split("**Vocabulary packet**", 1)[0] ?? "";
    const vocabulary = record.split("**Vocabulary packet**", 2)[1] ?? "";
    const prompt = comprehension.match(/^- Prompt: (.+)$/mu)?.[1] ?? "";
    const correct = comprehension.match(/^- Correct answer: (.+)$/mu)?.[1] ?? "";
    const distractorA = comprehension.match(/^- Distractor A: (.+)$/mu)?.[1] ?? "";
    const distractorB = comprehension.match(/^- Distractor B: (.+)$/mu)?.[1] ?? "";
    const correctFeedback = comprehension.match(/^- Correct feedback: (.+)$/mu)?.[1] ?? "";
    const tryAgainFeedback = comprehension.match(/^- Try-again feedback: (.+)$/mu)?.[1] ?? "";
    const cards = [...vocabulary.matchAll(/^- \*\*([^*]+)\*\* — Definition: (.+?) Used in a sentence: (.+)$/gmu)].map((match) => ({
      word: match[1], definition: match[2], sentence: match[3], properNoun: false,
    }));
    const source = plainMarkdownLink(field(record, "Source"));
    const paragraphs = spoken.split(/\n\s*\n/u).map((paragraph) => paragraph.replace(/\s+/gu, " ").trim()).filter(Boolean);
    assert.equal(cards.length, 3, `${id}: vocabulary count`);
    assert.equal(spoken.split(/\s+/u).filter(Boolean).length, spokenWordCount, `${id}: word count`);
    return {
      id,
      title,
      form,
      spokenWordCount,
      paragraphs,
      source,
      rights: field(record, "Rights"),
      selectionNote: field(record, "Selection note"),
      comprehension: { prompt, correct, distractors: [distractorA, distractorB], correctFeedback, tryAgainFeedback },
      vocabulary: cards,
      reviewStatus: "canonical-first-playtest-subject-to-recorded-review",
    };
  });
  assert.equal(records.length, expectedCounts[site], `${site}: passage count`);
  decks[site] = records;
}

assert.equal(Object.values(decks).flat().length, 53, "canonical passage count");

const banner = "// Generated from docs/content/FIRST_SIX_CANONICAL_READING_MANUSCRIPT_2026-08-21.md.\n// Do not edit this file directly; update the reviewed manuscript and rerun npm run generate:first-six-content.\n\n";
const moduleText = `${banner}const DATA = ${JSON.stringify(decks, null, 2)};\n\nfunction deepFreeze(value) {\n  if (!value || typeof value !== \"object\" || Object.isFrozen(value)) return value;\n  for (const child of Object.values(value)) deepFreeze(child);\n  return Object.freeze(value);\n}\n\nexport const FIRST_SIX_CANONICAL_PASSAGES = deepFreeze(DATA);\nexport const FIRST_SIX_CANONICAL_PASSAGE_COUNT = Object.values(FIRST_SIX_CANONICAL_PASSAGES).flat().length;\n`;
writeFileSync(fileURLToPath(outputUrl), moduleText);
console.log(`Generated ${Object.values(decks).flat().length} canonical passages at ${fileURLToPath(outputUrl)}`);
